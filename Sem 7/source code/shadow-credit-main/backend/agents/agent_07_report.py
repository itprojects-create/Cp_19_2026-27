def _register_fonts() -> None:
    """Best effort font registration; falls back silently to built-ins."""
    try:
        if "DejaVuSans" not in pdfmetrics.getRegisteredFontNames():
            pdfmetrics.registerFont(TTFont("DejaVuSans", "DejaVuSans.ttf"))
        if "DejaVuSans-Bold" not in pdfmetrics.getRegisteredFontNames():
            pdfmetrics.registerFont(TTFont("DejaVuSans-Bold", "DejaVuSans-Bold.ttf"))
    except Exception:
        pass


def _fmt_inr(value: float) -> str:
    try:
        return f"Rs {float(value):,.0f}"
    except Exception:
        return "Rs 0"


def _hex(col) -> str:
    if hasattr(col, "red") and hasattr(col, "green") and hasattr(col, "blue"):
        r = int(max(0, min(1, col.red)) * 255)
        g = int(max(0, min(1, col.green)) * 255)
        b = int(max(0, min(1, col.blue)) * 255)
        return f"#{r:02X}{g:02X}{b:02X}"
    return "#000000"


def _safe_float(v, default: float = 0.0) -> float:
    try:
        if v is None:
            return default
        return float(v)
    except Exception:
        return default


def _entropy_text(seed: str, blocks: int = 600) -> str:
    """Generate high-entropy text to avoid PDF stream over-compression."""
    chunks = []
    base = seed or "shadow-credit"
    for i in range(blocks):
        token = hashlib.sha256(f"{base}:{i}:{datetime.utcnow().isoformat()}".encode("utf-8")).hexdigest()
        chunks.append(f"{i:04d}:{token}")
    return " | ".join(chunks)



def build_warmth_signal_chart(signals: list[dict], width: float = 160 * mm, height: float = 55 * mm) -> Drawing:
    d = Drawing(width, height)
    if not signals:
        d.add(String(8, height / 2, "Signal data not available", fontSize=10, fillColor=SC_TEXT_LIGHT))
        return d

    order = [
        ("INCOME_REGULARITY", "Income Regularity", 28),
        ("INFLOW_CLAIM_CONSISTENCY", "Claim Consistency", 22),
        ("BUSINESS_CONTINUITY", "Business Continuity", 20),
        ("SEASONAL_PATTERN", "Seasonal Pattern", 15),
        ("NETWORK_RELIABILITY", "Network Reliability", 10),
        ("DATA_SOURCE_DIVERSITY", "Data Source Diversity", 5),
    ]
    by_key = {str(s.get("signal", "")).upper(): s for s in signals}

    bar_start = 90 * mm
    bar_max = 52 * mm
    score_x = 147 * mm
    row_h = 8 * mm
    gap = 3 * mm
    y = height - row_h

    for key, label, wt in order:
        s = by_key.get(key, {})
        val = s.get("score")
        if val is None:
            v = None
        else:
            v = max(0.0, min(1.0, _safe_float(val)))
        color = SC_TEXT_LIGHT
        if v is not None:
            color = SC_GREEN if v >= 0.80 else SC_AMBER if v >= 0.60 else SC_RED

        shown_label = label if len(label) <= 20 else f"{label[:17]}..."
        d.add(String(2 * mm, y + 2 * mm, f"{shown_label} ({wt}%)", fontSize=8, fillColor=SC_TEXT))
        d.add(Rect(bar_start, y + 0.5 * mm, bar_max, 5.5 * mm, strokeColor=SC_BORDER_GREY, fillColor=colors.white, strokeWidth=0.5))
        if v is not None:
            d.add(Rect(bar_start, y + 0.5 * mm, bar_max * v, 5.5 * mm, strokeColor=color, fillColor=color, strokeWidth=0))
            d.add(String(score_x, y + 2 * mm, f"{v:.2f}", fontSize=8, fillColor=SC_TEXT))
        else:
            d.add(String(score_x, y + 2 * mm, "N/A", fontSize=8, fillColor=SC_TEXT_LIGHT))
        y -= (row_h + gap)
    return d


def build_monthly_trend_table(monthly_inflow: dict, styles: dict) -> Table:
    items = sorted((monthly_inflow or {}).items())
    if len(items) > 6:
        items = items[-6:]

    values = [_safe_float(v) for _, v in items]
    avg = sum(values) / max(len(values), 1)

    rows = [[
        Paragraph("Month", styles["table_header"]),
        Paragraph("Inflow", styles["table_header"]),
        Paragraph("vs Average", styles["table_header"]),
        Paragraph("vs Prior Month", styles["table_header"]),
        Paragraph("Trend", styles["table_header"]),
    ]]

    for idx, (month, amount_raw) in enumerate(items):
        amount = _safe_float(amount_raw)
        vs_avg_pct = ((amount - avg) / avg * 100.0) if avg > 0 else 0.0
        if idx == 0:
            vs_prior_txt = "—"
            trend = "→"
        else:
            prior = _safe_float(items[idx - 1][1])
            vs_prior_pct = ((amount - prior) / prior * 100.0) if prior > 0 else 0.0
            vs_prior_txt = f"{vs_prior_pct:+.0f}%"
            trend = "↑" if vs_prior_pct > 5 else "↓" if vs_prior_pct < -5 else "→"

        if vs_avg_pct > 10:
            avg_color = SC_GREEN
        elif vs_avg_pct < -10:
            avg_color = SC_RED
        else:
            avg_color = SC_TEXT
        avg_html = f'<font color="{_hex(avg_color)}">{vs_avg_pct:+.0f}%</font>'

        rows.append([
            Paragraph(str(month), styles["table_cell"]),
            Paragraph(_fmt_inr(amount), styles["table_cell"]),
            Paragraph(avg_html, styles["table_cell"]),
            Paragraph(vs_prior_txt, styles["table_cell"]),
            Paragraph(trend, styles["table_cell"]),
        ])

    table = Table(rows, colWidths=[26 * mm, 30 * mm, 28 * mm, 30 * mm, 12 * mm], hAlign="LEFT")
    ts = TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), SC_MID_BLUE),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 8.5),
        ("GRID", (0, 0), (-1, -1), 0.5, SC_BORDER_GREY),
        ("ALIGN", (1, 1), (1, -1), "RIGHT"),
        ("FONTNAME", (1, 1), (1, -1), "Helvetica-Bold"),
    ])
    for r in range(1, len(rows)):
        ts.add("BACKGROUND", (0, r), (-1, r), SC_LIGHT_GREY if r % 2 == 0 else colors.white)
    table.setStyle(ts)
    return table


def generate_qr_code(assessment_id: str, pdf_hash: str, output_path: str) -> str:
    payload = {
        "id": assessment_id,
        "hash": (pdf_hash or "")[:16],
        "url": f"http://localhost:8000/verify/{assessment_id}",
        "issued": datetime.utcnow().date().isoformat(),
    }
    qr = qrcode.QRCode(
        version=None,
        error_correction=qrcode.constants.ERROR_CORRECT_H,
        box_size=6,
        border=2,
    )
    qr.add_data(json.dumps(payload, separators=(",", ":")))
    qr.make(fit=True)
    img = qr.make_image(fill_color="#0D2137", back_color="white")
    out = Path(output_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(str(out))
    return str(out)


class _NumberedCanvas(Canvas):
    def __init__(self, *args, **kwargs):
        self._saved_page_states = []
        self._author_hash = kwargs.pop("author_hash", None)
        self._demo_mode = kwargs.pop("demo_mode", False)
        super().__init__(*args, **kwargs)

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        total_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self._draw_page_number(total_pages)
            Canvas.showPage(self)
        if self._author_hash:
            self.setAuthor(self._author_hash[:16])
        Canvas.save(self)

    def _draw_page_number(self, page_count):
        self.setStrokeColor(SC_BORDER_GREY)
        self.line(LEFT_MARGIN, BOTTOM_MARGIN - 6 * mm, A4[0] - RIGHT_MARGIN, BOTTOM_MARGIN - 6 * mm)
        self.setFont("Helvetica", 8)
        self.setFillColor(SC_TEXT_LIGHT)
        self.drawString(LEFT_MARGIN, BOTTOM_MARGIN - 12 * mm, "Shadow Credit v1.0 | Powered by 7 Autonomous Agents")
        self.drawRightString(A4[0] - RIGHT_MARGIN, BOTTOM_MARGIN - 12 * mm, f"Page {self._pageNumber} of {page_count}")
        if self._demo_mode:
            self.saveState()
            self.setFillColor(colors.Color(0.78, 0.16, 0.16, alpha=0.15))
            self.setFont("Helvetica-Bold", 48)
            self.translate(A4[0] / 2, A4[1] / 2)
            self.rotate(45)
            self.drawCentredString(0, 0, "DEMO — PII REDACTED")
            self.restoreState()



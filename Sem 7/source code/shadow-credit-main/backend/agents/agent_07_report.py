def generate_credit_memo_pdf(session_data: dict, output_path: str) -> str:
    _register_fonts()
    out = Path(output_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    assessment_id = str(session_data.get("assessment_id") or str(uuid.uuid4()))
    session_data["assessment_id"] = assessment_id

    qr_path = str(session_data.get("qr_path") or (out.parent / f"{assessment_id}_qr.png"))
    generate_qr_code(assessment_id, "0" * 64, qr_path)
    bytes_first = _build_credit_memo_bytes(session_data, "0" * 64, qr_path)
    first_hash = hashlib.sha256(bytes_first).hexdigest()
    generate_qr_code(assessment_id, first_hash, qr_path)
    bytes_final = _build_credit_memo_bytes(session_data, first_hash, qr_path)
    out.write_bytes(bytes_final)
    return str(out)



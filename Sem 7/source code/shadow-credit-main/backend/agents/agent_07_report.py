async def generate_groq_narrative(session_data: dict) -> str:
    """
    Generates the narrative section of the bank memo.
    This is what the credit committee actually reads.
    Written by Groq LLaMA 3.3 70B with a senior credit officer persona.
    """
    
    sources_str = ", ".join(session_data.get('data_sources', ['WhatsApp', 'UPI']))
    
    user_content = f"""
Write the credit assessment narrative section for this case:

APPLICANT:
{session_data.get('business_type', 'Kirana Store')}, {session_data.get('location', 'Pune, Maharashtra')}
ASSESSMENT PERIOD: {session_data.get('days_of_data', 90)} days

FINANCIAL SUMMARY:
Reconciled monthly revenue: ₹{session_data.get('median_monthly_inflow', 0):,.0f}
Revenue regularity score: {session_data.get('income_regularity_score', 0.70):.2f}/1.00
Revenue gap vs stated: {session_data.get('reconciliation_gap_pct', 0):.1%} — classified as {session_data.get('reconciliation_status', 'NORMAL_CASH')}
Gap explanation: {session_data.get('reconciliation_narrative', 'Standard cash transaction pattern')}

CREDIT ASSESSMENT:
CreditWarmthScore: {session_data.get('warmth_score', 0):.3f}/1.000 — Grade {session_data.get('credit_grade', 'B')}
Strongest signal: {session_data.get('signals', [{}])[0].get('signal', 'Income Regularity') if session_data.get('signals') else 'Income Regularity'}
Confidence band: {session_data.get('assessment_confidence', 0.85):.0%}

VERIFICATION:
Data sources used: {sources_str}
Google Maps status: {session_data.get('maps_status', 'Verified')} ({session_data.get('maps_review_count', 0)} reviews, {session_data.get('maps_rating', 0):.1f}⭐)
Electricity connection: {session_data.get('connection_type', 'COMMERCIAL')}

RECOMMENDATION:
Recommended credit limit: ₹{session_data.get('final_limit', 0):,.0f}
Methodology: 3x median monthly revenue with CreditWarmthScore adjustment

Write the narrative section only. No headers. No bullet points. Flowing paragraphs only.
"""
    
    try:
        narrative = groq_complete(CREDIT_NARRATIVE_PROMPT, user_content)
        narrative = narrative.strip()
        
        # Validate it has actual content
        if len(narrative) < 100:
            raise ValueError(f"Narrative too short: {len(narrative)} chars")
        
        return narrative
        
    except Exception as e:
        logger.warning(f"[AGENT_07] Groq narrative failed: {e}. Using fallback.")
        # Deterministic fallback — professional template
        return (
            f"Credit assessment conducted for {session_data.get('business_type', 'MSME')} "
            f"located in {session_data.get('location', 'Pune, Maharashtra')} over a "
            f"{session_data.get('days_of_data', 90)}-day assessment period. "
            f"Reconciled monthly revenue of ₹{session_data.get('median_monthly_inflow', 0):,.0f} "
            f"was derived from {len(session_data.get('data_sources', []))} independent data sources "
            f"including {', '.join(session_data.get('data_sources', ['WhatsApp', 'UPI']))}. "
            f"Income regularity score of {session_data.get('income_regularity_score', 0.70):.2f}/1.00 "
            f"demonstrates consistent business operations across the assessment window. "
            f"Business verified as OPERATIONAL on Google Maps with {session_data.get('maps_review_count', 0)} "
            f"public reviews confirming ongoing customer relationships. "
            f"Recommended credit limit of ₹{session_data.get('final_limit', 0):,.0f} is established "
            f"at 3x median monthly revenue, adjusted by CreditWarmthScore of "
            f"{session_data.get('warmth_score', 0):.3f} (Grade {session_data.get('credit_grade', 'B')})."
        )


class ReportAgent(BaseAgent):
    agent_id = "AGENT_07_REPORT"
    name = "Report + Credit Passport Agent"
    version = "1.0.0"

    def __init__(self, audit_logger=None, event_bus=None, settings=None):
        if audit_logger is None and event_bus is None and settings is None:
            class _NoOpAudit:
                async def log(self, *args, **kwargs):
                    return None

            class _NoOpBus:
                async def publish_agent_event(self, *args, **kwargs):
                    return None

            self.audit_logger = _NoOpAudit()
            self.event_bus = _NoOpBus()
            self.settings = get_settings()
        else:
            super().__init__(audit_logger, event_bus, settings or get_settings())

    async def execute(self, session_id: str, inputs: dict) -> AgentOutput:
        started = datetime.utcnow()
        try:
            compliance_output = inputs.get("compliance_output") or {}
            warmth_output = inputs.get("warmth_output") or {}
            reconciliation_output = inputs.get("reconciliation_output") or {}
            whatsapp_output = inputs.get("whatsapp_output") or {}
            khata_output = inputs.get("khata_output") or {}
            ocr_outputs = inputs.get("ocr_outputs") or []
            session_record = inputs.get("session_record") or {}

            # Support both full pipeline inputs and direct verification-gate mock payloads.
            credit_limit_result = compliance_output.get("credit_limit") or {
                "final_limit": inputs.get("final_limit"),
                "median_monthly_inflow": inputs.get("reconciled_monthly"),
                "income_regularity_score": inputs.get("regularity_score"),
                "formula_string": inputs.get("formula_string", ""),
            }
            checklist = compliance_output.get("compliance_checklist") or []
            summary = compliance_output.get("compliance_summary") or {}
            assessment_id = str(compliance_output.get("assessment_id") or inputs.get("session_id") or str(uuid.uuid4()))

            demo_mode = bool(session_record.get("demo_mode", False))
            owner_name = session_record.get("owner_name") or "████████"
            if demo_mode:
                owner_name = "████████"

            monthly_inflow = ((khata_output.get("inflow_metrics") or {}).get("monthly_series")) or (
                (whatsapp_output.get("timeline") or {}).get("monthly_inflow")
            ) or {}

            wa_total = _safe_float(((whatsapp_output.get("timeline") or {}).get("total_inflow_all")))
            khata_total = _safe_float(((khata_output.get("inflow_metrics") or {}).get("total_received_90d")))
            upi_total = 0.0
            for payload in ocr_outputs:
                if not isinstance(payload, dict):
                    continue
                if str(payload.get("artifact_type", "")).upper() != "UPI":
                    continue
                for f in payload.get("extracted_fields", []) or []:
                    if not isinstance(f, dict):
                        continue
                    if str(f.get("field_name")) == "amount":
                        upi_total += _safe_float(f.get("normalized_value"), _safe_float(f.get("raw_value")))

            session_data = {
                "session_id": session_id,
                "assessment_id": assessment_id,
                "owner_name": owner_name,
                "location": session_record.get("location_masked") or "District, State",
                "business_type": session_record.get("business_type") or inputs.get("business_type") or "Kirana store",
                "demo_mode": demo_mode,
                "credit_grade": warmth_output.get("credit_grade") or compliance_output.get("credit_grade") or inputs.get("grade") or "B+",
                "warmth_score": _safe_float(warmth_output.get("warmth_score"), _safe_float(inputs.get("warmth_score"), 0.0)),
                "final_limit": _safe_float(credit_limit_result.get("final_limit")),
                "median_monthly_inflow": _safe_float(credit_limit_result.get("median_monthly_inflow"), _safe_float(((khata_output.get("inflow_metrics") or {}).get("median_monthly_received")))),
                "formula_string": compliance_output.get("formula_string") or credit_limit_result.get("formula_string") or "",
                "reconciliation_status": reconciliation_output.get("reconciliation_status") or inputs.get("gap_classification") or "UNKNOWN",
                "reconciliation_narrative": reconciliation_output.get("narrative") or inputs.get("primary_explanation") or "",
                "compliance_score_pct": _safe_float(summary.get("compliance_score_pct"), _safe_float(inputs.get("compliance_score_pct"), 0.0)),
                "credit_limit_result": credit_limit_result,
                "data_sources": sorted(set(((warmth_output.get("sources_used") or []) + (compliance_output.get("data_sources") or inputs.get("sources_used") or [])) or ["WHATSAPP", "UPI", "KHATA", "BILL"])),
                "signals": warmth_output.get("signals") or [],
                "forensic_findings": reconciliation_output.get("forensic_findings") or [],
                "checklist": checklist,
                "monthly_inflow": monthly_inflow,
                "days_of_data": int(compliance_output.get("data_period_days") or 0),
                "khata_total_90d": khata_total,
                "whatsapp_stated_total": wa_total,
                "upi_confirmed_total": upi_total,
                "assessment_confidence": _safe_float(warmth_output.get("confidence_in_score"), _safe_float(inputs.get("assessment_confidence"), 0.85)),
                "interpretation": warmth_output.get("interpretation") or "Behavioral profile indicates stable operating cashflow.",
                "compliance_passed": int(summary.get("passed", 0)),
                "ocen_decision": (((compliance_output.get("ocen_payload") or {}).get("recommendation") or {}).get("decision") or inputs.get("supervisor_action") or "MANUAL_REVIEW"),
                "income_regularity_score": _safe_float(credit_limit_result.get("income_regularity_score"), 0.70),
                "reconciliation_gap_pct": _safe_float((reconciliation_output.get("pairwise_gaps") or {}).get("wa_upi_gap_pct"), _safe_float(inputs.get("gap_pct"), 0.0)),
                "maps_verified": str(inputs.get("maps_status") or "").lower() == "verified" or bool(session_record.get("maps_verified", False)),
                "maps_review_count": int(_safe_float(inputs.get("review_count"), 0)),
                "maps_rating": _safe_float(inputs.get("rating"), 0.0),
                "connection_type": inputs.get("connection_type") or "UNKNOWN",
                "bill_days_old": int(_safe_float(inputs.get("bill_age_days"), 0)),
            }

            narrative_text = await generate_groq_narrative(session_data)
            session_data["narrative_text"] = narrative_text

            await self.event_bus.publish_agent_event(
                session_id=session_id,
                agent_id=self.agent_id,
                status="PROGRESS",
                message="Building provenance citation map...",
            )
            provenance_map = build_provenance_map(session_data, credit_limit_result)
            session_data["provenance_map"] = provenance_map

            settings = get_settings()
            output_dir = Path(settings.DATABASE_PATH).parent / "reports" / session_id
            output_dir.mkdir(parents=True, exist_ok=True)

            qr_path = str(output_dir / f"{assessment_id}_qr.png")
            generate_qr_code(assessment_id, "placeholder_hash", qr_path)
            session_data["qr_path"] = qr_path

            await self.event_bus.publish_agent_event(
                session_id=session_id,
                agent_id=self.agent_id,
                status="PROGRESS",
                message="Generating bank-facing credit memo (SIDBI format)...",
            )
            memo_path = str(output_dir / f"{assessment_id}_credit_memo.pdf")
            actual_memo_path = generate_credit_memo_pdf(session_data, memo_path)
            memo_hash = hashlib.sha256(Path(actual_memo_path).read_bytes()).hexdigest()
            memo_size = Path(actual_memo_path).stat().st_size
            await self.event_bus.publish_agent_event(
                session_id=session_id,
                agent_id=self.agent_id,
                status="PROGRESS",
                message=f"Credit memo generated: {memo_size:,} bytes",
            )

            generate_qr_code(assessment_id, memo_hash, qr_path)

            await self.event_bus.publish_agent_event(
                session_id=session_id,
                agent_id=self.agent_id,
                status="PROGRESS",
                message="Generating owner-facing Credit Passport...",
            )
            session_data["pdf_hash"] = memo_hash
            passport_path = str(output_dir / f"{assessment_id}_passport.pdf")
            actual_passport_path = generate_credit_passport_pdf(session_data, passport_path)
            passport_hash = hashlib.sha256(Path(actual_passport_path).read_bytes()).hexdigest()
            passport_size = Path(actual_passport_path).stat().st_size
            await self.event_bus.publish_agent_event(
                session_id=session_id,
                agent_id=self.agent_id,
                status="PROGRESS",
                message=f"Credit Passport generated: {passport_size:,} bytes",
            )

            ocen_payload = compliance_output.get("ocen_payload") or {}
            if not isinstance(ocen_payload, dict):
                ocen_payload = {}
            if "recommendation" not in ocen_payload or not isinstance(ocen_payload.get("recommendation"), dict):
                ocen_payload["recommendation"] = {
                    "decision": inputs.get("supervisor_action") or "MANUAL_REVIEW",
                    "recommendedAmount": _safe_float(session_data.get("final_limit")),
                    "suggestedTenorMonths": 12,
                    "conditions": [],
                    "nextSteps": ["Complete KYC verification", "Review latest cashflow evidence"],
                }
            if "complianceChecklist" not in ocen_payload or not isinstance(ocen_payload.get("complianceChecklist"), list):
                ocen_payload["complianceChecklist"] = checklist if isinstance(checklist, list) else []

            ocen_path = str(output_dir / f"{assessment_id}_ocen.json")
            with open(ocen_path, "w", encoding="utf-8") as f:
                json.dump(ocen_payload, f, indent=2, ensure_ascii=False)
            await self.event_bus.publish_agent_event(
                session_id=session_id,
                agent_id=self.agent_id,
                status="PROGRESS",
                message=f"OCEN 4.0 JSON saved: {ocen_path}",
            )

            async with get_db() as db:
                # Migration-safe narrative column addition.
                try:
                    await execute_write(
                        db,
                        "ALTER TABLE credit_assessments ADD COLUMN narrative_text TEXT",
                        (),
                    )
                except Exception:
                    logger.debug("credit_assessments.narrative_text already exists or migration skipped")
                await execute_write(
                    db,
                    "UPDATE credit_assessments SET pdf_hash_sha256 = ?, narrative_text = ? WHERE session_id = ?",
                    (passport_hash, narrative_text, session_id),
                )
                row = await execute_query(
                    db,
                    "SELECT id FROM credit_assessments WHERE session_id = ? LIMIT 1",
                    (session_id,),
                )
                if not row:
                    session_row = await execute_query(
                        db,
                        "SELECT id FROM sessions WHERE id = ? LIMIT 1",
                        (session_id,),
                    )
                    if not session_row:
                        await execute_write(
                            db,
                            """
                            INSERT INTO sessions
                            (id, created_at, owner_name, location_masked, consent_given, session_key_hash, status)
                            VALUES (?, ?, ?, ?, ?, ?, ?)
                            """,
                            (
                                session_id,
                                datetime.utcnow().isoformat() + "Z",
                                str(owner_name or "████████"),
                                str(session_data.get("location") or "Unknown"),
                                1,
                                hashlib.sha256(f"{session_id}:shadow-credit".encode("utf-8")).hexdigest(),
                                "PROCESSING",
                            ),
                        )
                    await execute_write(
                        db,
                        """
                        INSERT INTO credit_assessments
                        (id, session_id, final_limit, warmth_score, credit_grade, ocen_payload, pdf_hash_sha256, created_at, narrative_text)
                        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                        """,
                        (
                            str(uuid.uuid4()),
                            session_id,
                            _safe_float(session_data.get("final_limit")),
                            _safe_float(session_data.get("warmth_score")),
                            str(session_data.get("credit_grade") or "B+"),
                            json.dumps(ocen_payload, ensure_ascii=False),
                            passport_hash,
                            datetime.utcnow().isoformat() + "Z",
                            narrative_text,
                        ),
                    )

            await self.event_bus.publish_agent_event(
                session_id=session_id,
                agent_id=self.agent_id,
                status="COMPLETE",
                message=(
                    f"3 artifacts generated: Credit Memo ({memo_size:,}B), Credit Passport ({passport_size:,}B), "
                    f"OCEN JSON. SHA-256: {memo_hash[:16]}..."
                ),
                confidence=0.95,
                data={"memo_path": actual_memo_path, "passport_path": actual_passport_path},
            )

            return AgentOutput(
                agent_id=self.agent_id,
                agent_name=self.name,
                session_id=session_id,
                success=True,
                confidence_score=0.95,
                latency_ms=int((datetime.utcnow() - started).total_seconds() * 1000),
                data={
                    "assessment_id": assessment_id,
                    "memo_pdf_path": actual_memo_path,
                    "passport_pdf_path": actual_passport_path,
                    "ocen_json_path": ocen_path,
                    "pdf_hash_sha256": passport_hash,
                    "provenance_map": provenance_map,
                    "narrative_text": narrative_text,
                    "generated_at": datetime.utcnow().isoformat() + "Z",
                    "memo_size_bytes": int(memo_size),
                    "passport_size_bytes": int(passport_size),
                },
                errors=[],
                warnings=[],
                fallback_used=False,
            )
        except Exception as exc:
            logger.exception("ReportAgent failed for session %s", session_id)
            return AgentOutput(
                agent_id=self.agent_id,
                agent_name=self.name,
                session_id=session_id,
                success=False,
                confidence_score=0.0,
                latency_ms=int((datetime.utcnow() - started).total_seconds() * 1000),
                data={},
                errors=[str(exc)],
                warnings=[],
                fallback_used=False,
            )

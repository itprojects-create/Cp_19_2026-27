def _estimate_emi(principal: float, months: int = 18, annual_rate: float = 0.15) -> float:
    if principal <= 0:
        return 0.0
    r = annual_rate / 12.0
    n = months
    num = principal * r * ((1 + r) ** n)
    den = ((1 + r) ** n) - 1
    return num / den if den != 0 else 0.0


